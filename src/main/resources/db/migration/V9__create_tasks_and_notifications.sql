CREATE TABLE work_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(20) NOT NULL CHECK (type IN ('TASK', 'FOLLOW_UP', 'REMINDER')),
    title VARCHAR(200) NOT NULL,
    description TEXT,
    conversation_id VARCHAR(24),
    assigned_user_id BIGINT NOT NULL REFERENCES users(id),
    created_by_user_id BIGINT NOT NULL REFERENCES users(id),
    due_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN', 'COMPLETED', 'CANCELLED')),
    priority VARCHAR(10) NOT NULL CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
    overdue_notified BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX work_tasks_assignee_due_idx ON work_tasks(assigned_user_id, due_at);
CREATE INDEX work_tasks_overdue_idx ON work_tasks(due_at) WHERE status = 'OPEN' AND overdue_notified = FALSE;

CREATE TABLE user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    type VARCHAR(50) NOT NULL,
    title VARCHAR(300) NOT NULL,
    resource_type VARCHAR(30),
    resource_id VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL,
    read_at TIMESTAMPTZ
);
CREATE INDEX user_notifications_user_date_idx ON user_notifications(user_id, created_at DESC, id DESC);
CREATE INDEX user_notifications_unread_idx ON user_notifications(user_id) WHERE read_at IS NULL;
