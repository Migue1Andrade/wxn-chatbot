CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    user_id BIGINT NULL,
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    type VARCHAR(20) NOT NULL CHECK (type IN ('HUMAN', 'BOT')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ NULL,
    CONSTRAINT members_user_tenant_fk FOREIGN KEY (company_id, user_id) REFERENCES users(company_id, id),
    CONSTRAINT members_human_user_check CHECK (type <> 'HUMAN' OR user_id IS NOT NULL)
);
CREATE INDEX members_company_idx ON members(company_id);
CREATE UNIQUE INDEX members_active_human_unique ON members(company_id, user_id)
    WHERE type = 'HUMAN' AND status = 'ACTIVE' AND deleted_at IS NULL;
