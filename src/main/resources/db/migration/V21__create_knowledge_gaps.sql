CREATE TABLE knowledge_gaps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id VARCHAR(120) NOT NULL,
    conversation_id VARCHAR(80) NOT NULL,
    reason VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    draft_article_id BIGINT REFERENCES knowledge_articles(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT knowledge_gaps_reason_check CHECK (reason IN ('NO_SOURCE')),
    CONSTRAINT knowledge_gaps_status_check CHECK (status IN ('OPEN', 'CONVERTED')),
    CONSTRAINT knowledge_gaps_request_conversation_unique UNIQUE (request_id, conversation_id)
);

CREATE INDEX knowledge_gaps_created_idx ON knowledge_gaps (created_at DESC, id DESC);
