CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    phone VARCHAR(20) CHECK (phone IS NULL OR phone ~ '^[+][1-9][0-9]{7,14}$'),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX users_phone_unique ON users(phone) WHERE phone IS NOT NULL;

CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id),
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    type VARCHAR(20) NOT NULL CHECK (type IN ('HUMAN', 'BOT')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT members_human_user_check CHECK (type <> 'HUMAN' OR user_id IS NOT NULL)
);
CREATE UNIQUE INDEX members_active_human_unique ON members(user_id)
    WHERE type = 'HUMAN' AND status = 'ACTIVE' AND deleted_at IS NULL;
