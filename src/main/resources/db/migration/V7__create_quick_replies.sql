CREATE TABLE quick_replies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    shortcut VARCHAR(50) NOT NULL,
    description VARCHAR(300),
    content TEXT NOT NULL,
    scope VARCHAR(20) NOT NULL CHECK (scope IN ('GLOBAL', 'PERSONAL')),
    owner_user_id BIGINT REFERENCES users(id),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    CHECK ((scope = 'GLOBAL' AND owner_user_id IS NULL) OR (scope = 'PERSONAL' AND owner_user_id IS NOT NULL))
);

CREATE UNIQUE INDEX quick_replies_global_shortcut_idx ON quick_replies (lower(shortcut))
    WHERE scope = 'GLOBAL' AND deleted_at IS NULL;
CREATE UNIQUE INDEX quick_replies_personal_shortcut_idx ON quick_replies (owner_user_id, lower(shortcut))
    WHERE scope = 'PERSONAL' AND deleted_at IS NULL;
