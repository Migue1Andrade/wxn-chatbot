CREATE TABLE whatsapp_channels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    provider VARCHAR(30) NOT NULL CHECK (provider IN ('MOCK', 'TWILIO')),
    phone_number VARCHAR(20) NULL CHECK (phone_number IS NULL OR phone_number ~ '^[+][1-9][0-9]{7,14}$'),
    external_channel_id VARCHAR(255) NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ NULL
);
CREATE INDEX whatsapp_channels_company_idx ON whatsapp_channels(company_id);
